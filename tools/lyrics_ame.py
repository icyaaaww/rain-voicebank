SMALL_YOON = set("ゃゅょぁぃぅぇぉ")
VOWELS = "あいうえお"


def split_syllables(text):
    """把歌词切成音节列表（每个元素是一个可唱的假名音节）。"""
    out = []
    for line in text.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        for ch in line:
            if ch in " 　、。・（）()「」!?！？":
                continue
            if ch == "っ":
                # 促音声库没有，跳过（真实的っ靠延续下一个辅音，这里简化处理）
                continue
            if ch == "ー":
                # 长音并入前一个
                if out:
                    out[-1] = out[-1] + "ー"
                continue
            if ch in SMALL_YOON and out and len(out[-1]) == 1:
                # 拗音：与前一个假名合并
                out[-1] = out[-1] + ch
                continue
            out.append(ch)
    return out


